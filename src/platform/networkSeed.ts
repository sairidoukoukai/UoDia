/** 同梱の `route.json` を読む。**Web 版もデスクトップ版も同じ道を通る。** */
export async function loadBundledNetworkDef(): Promise<string> {
  const url = (await import('../../data/route.json?url')).default;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`route.json を取得できません: ${String(response.status)}`);
  }
  return response.text();
}
